package com.matlasystems.chat.common.enums;

/**
 * Represents the lifecycle status of a group.
 */
public enum GroupStatus {

    /**
     * Group is active and available.
     */
    ACTIVE,

    /**
     * Group is temporarily inactive.
     */
    INACTIVE,

    /**
     * Group has been archived.
     */
    ARCHIVED,

    /**
     * Group has been deleted.
     */
    DELETED

}